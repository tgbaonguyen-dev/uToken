import 'daily_doc.dart';

/// A process quality metric from the efficiency document.
class ProcessMetric {
  const ProcessMetric(
      {required this.metric, required this.label, this.provider, this.value});
  final String metric, label;
  final String? provider;
  final double? value;
  factory ProcessMetric.fromMap(JsonMap m) => ProcessMetric(
      metric: readString(m['metric']) ?? '',
      label: readString(m['label']) ?? 'no_data',
      provider: readString(m['provider']),
      value: readDouble(m['value']));
}

/// One model/provider/task-group comparison from the efficiency document.
class SetupMetric {
  const SetupMetric(
      {required this.provider,
      required this.model,
      required this.taskGroup,
      required this.tasks,
      required this.verdict,
      required this.crossTool,
      this.sr,
      this.cpstMicro,
      this.effort,
      this.srCiLow,
      this.srCiHigh,
      this.mde,
      this.verified = 0,
      this.redoRate,
      this.confidence});
  final String provider, model, taskGroup, verdict;
  final int tasks, verified;
  final bool crossTool;
  final double? sr, srCiLow, srCiHigh, mde, redoRate;
  final int? cpstMicro;
  final String? effort, confidence;

  /// "gpt-5.6 · high" when the reasoning effort is known.
  String get name =>
      effort == null || effort!.isEmpty ? model : '$model · $effort';
  factory SetupMetric.fromMap(JsonMap m) => SetupMetric(
      provider: readString(m['provider']) ?? '',
      model: readString(m['model']) ?? '',
      taskGroup: readString(m['task_group']) ?? '',
      tasks: readInt(m['n_tasks']) ?? 0,
      verdict: readString(m['verdict']) ?? 'insufficient',
      crossTool: readBool(m['cross_tool']) ?? false,
      sr: readDouble(m['sr']),
      cpstMicro: readInt(m['cpst_micro']),
      effort: m['effort'] as String?,
      srCiLow: readDouble(m['sr_ci_low']),
      srCiHigh: readDouble(m['sr_ci_high']),
      mde: readDouble(m['mde']),
      verified: readInt(m['n_verified']) ?? 0,
      redoRate: readDouble(m['redo_rate']),
      confidence: m['confidence'] as String?);
}

/// Current efficiency report generated by desktop.
class EfficiencyDoc {
  const EfficiencyDoc(
      {required this.periodStart,
      required this.periodEnd,
      required this.generatedAt,
      required this.processMetrics,
      required this.setups,
      this.undeterminedTasks});
  final String periodStart, periodEnd, generatedAt;
  final List<ProcessMetric> processMetrics;
  final List<SetupMetric> setups;
  final int? undeterminedTasks;
  factory EfficiencyDoc.fromMap(JsonMap m) => EfficiencyDoc(
      periodStart: readString(m['period_start']) ?? '',
      periodEnd: readString(m['period_end']) ?? '',
      generatedAt: readString(m['generated_at']) ?? '',
      processMetrics: readList(m['process_metrics'])
          .map((e) => ProcessMetric.fromMap(readMap(e)))
          .toList(),
      setups: readList(m['setups'])
          .map((e) => SetupMetric.fromMap(readMap(e)))
          .toList(),
      undeterminedTasks: readInt(m['undetermined_tasks']));
}

/// A source metric attached to an AI insight.
class Evidence {
  const Evidence(
      {required this.metric, required this.label, required this.value});
  final String metric, label, value;
  factory Evidence.fromMap(JsonMap m) => Evidence(
      metric: readString(m['metric']) ?? '',
      label: readString(m['label']) ?? '',
      value: readString(m['value']) ?? '');
}

/// A single actionable AI recommendation.
class Insight {
  const Insight(
      {required this.id,
      required this.title,
      required this.severity,
      required this.category,
      required this.evidence,
      required this.recommendation,
      required this.confidence,
      this.provider,
      this.estimatedImpact,
      this.estimatedSavingMicroPerMonth,
      this.why = '',
      this.steps = const []});
  final String id, title, severity, category, recommendation, confidence;

  /// Why the pattern costs tokens (newer desktop reviews only).
  final String why;

  /// Concrete actions in order (newer desktop reviews only).
  final List<String> steps;
  final String? provider, estimatedImpact;
  final int? estimatedSavingMicroPerMonth;
  final List<Evidence> evidence;
  factory Insight.fromMap(JsonMap m) => Insight(
          id: readString(m['id']) ?? '',
          title: readString(m['title']) ?? '',
          severity: readString(m['severity']) ?? 'low',
          category: readString(m['category']) ?? '',
          evidence: readList(m['evidence'])
              .map((e) => Evidence.fromMap(readMap(e)))
              .toList(),
          recommendation: readString(m['recommendation']) ?? '',
          confidence: readString(m['confidence']) ?? 'low',
          provider: readString(m['provider']),
          estimatedImpact: readString(m['estimated_impact']),
          estimatedSavingMicroPerMonth:
              readInt(m['estimated_saving_micro_per_month']),
          why: readString(m['why']) ?? '',
          steps: [
            for (final s in readList(m['steps']))
              if (s is String && s.trim().isNotEmpty) s.trim()
          ]);
}

/// One of the six scored review dimensions (cache, context, ...).
class InsightDimension {
  const InsightDimension({required this.id, required this.comment, this.score});
  final String id, comment;
  final int? score;
  factory InsightDimension.fromMap(JsonMap m) => InsightDimension(
      id: m['id'] as String? ?? '',
      comment: m['comment'] as String? ?? '',
      score: readInt(m['score']));
}

/// Current AI insight report, including optional evaluator metadata.
class InsightsDoc {
  const InsightsDoc(
      {required this.status,
      required this.generatedAt,
      required this.headline,
      required this.insights,
      this.dimensions = const [],
      this.score,
      this.grade,
      this.errorCode,
      this.periodStart,
      this.periodEnd,
      this.provider,
      this.model,
      this.reviewMode,
      this.reviewFrom,
      this.reviewThrough});
  final String status, generatedAt, headline;
  final List<Insight> insights;
  final List<InsightDimension> dimensions;
  final double? score;
  final String? grade, errorCode, periodStart, periodEnd, provider, model;
  final String? reviewMode, reviewFrom, reviewThrough;
  factory InsightsDoc.fromMap(JsonMap m) => InsightsDoc(
      status: readString(m['status']) ?? 'failed',
      generatedAt: readString(m['generated_at']) ?? '',
      headline: readString(m['headline']) ?? '',
      insights: readList(m['insights'])
          .map((e) => Insight.fromMap(readMap(e)))
          .toList(),
      dimensions: ((m['dimensions'] as List?) ?? const [])
          .map((e) =>
              InsightDimension.fromMap((e as Map).cast<String, dynamic>()))
          .toList(),
      score: readDouble(m['score']),
      grade: readString(m['grade']),
      errorCode: readString(m['error_code']),
      periodStart: readString(m['period_start']),
      periodEnd: readString(m['period_end']),
      provider: readString(m['provider']),
      model: readString(m['model']),
      reviewMode: readString(m['review_mode']),
      reviewFrom: readString(m['review_from']),
      reviewThrough: readString(m['review_through']));
}

/// A message an admin sent from the web console: to everyone
/// (`announcements/{id}`) or to one account (`users/{uid}/inbox/{id}`).
class Notice {
  const Notice(
      {required this.id,
      required this.title,
      required this.body,
      required this.level,
      required this.personal,
      this.createdAt,
      this.expiresAt});
  final String id, title, body;

  /// info, warning or critical.
  final String level;

  /// Sent to this account only (not a broadcast).
  final bool personal;
  final DateTime? createdAt, expiresAt;

  bool isLive(DateTime now) => expiresAt == null || expiresAt!.isAfter(now);

  factory Notice.fromMap(String id, JsonMap m, {required bool personal}) =>
      Notice(
        id: personal ? 'inbox/$id' : id,
        title: readString(m['title']) ?? '',
        body: readString(m['body']) ?? '',
        level: const ['info', 'warning', 'critical'].contains(m['level'])
            ? m['level'] as String
            : 'info',
        personal: personal,
        createdAt: _readTime(m['created_at']),
        expiresAt: _readTime(m['expires_at']),
      );
}

DateTime? _readTime(Object? v) {
  if (v is DateTime) return v;
  if (v is String) return DateTime.tryParse(v);
  try {
    // Firestore Timestamp without importing cloud_firestore here.
    return (v as dynamic)?.toDate() as DateTime?;
  } catch (_) {
    return null;
  }
}
